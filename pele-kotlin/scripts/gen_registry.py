#!/usr/bin/env python3
# PORT: JVM-only helper with no upstream counterpart (see UPDATE.md).
# Regenerates diagrams/Registry.kt from upstream's src/diagrams/registry.ts, listing the
# diagram types that have been ported (those with an Index.kt), in upstream's order.
import os, re
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
kt = os.path.join(here, '..', 'src', 'main', 'kotlin', 'pele', 'diagrams')
ts = open(os.path.join(root, 'src', 'diagrams', 'registry.ts')).read()
dirs = dict(re.findall(r"import \{ (\w+) \} from '\./(\w+)/index\.js';", ts))
order = re.findall(r"^  (\w+),$", ts.split('export const all = [')[1].split('];')[0], re.M)
ported = [n for n in order if os.path.exists(os.path.join(kt, dirs[n].replace('class', 'classdiagram') if dirs[n] == 'class' else dirs[n], 'Index.kt'))]
pkg = lambda n: 'classdiagram' if dirs[n] == 'class' else dirs[n]
imports = '\n'.join(sorted(f'import pele.diagrams.{pkg(n)}.{n}' for n in ported))
body = ''.join(f'  {n},\n' for n in ported)
open(os.path.join(kt, 'Registry.kt'), 'w').write(f'''// Ported from Pele src/diagrams/registry.ts @ bdbad5df4dea13b9a14a83a92aed62c4769e49f5
// Copyright (c) 2026 kepano, MIT License.
package pele.diagrams

import pele.Diagram
{imports}

// Every implemented diagram type. Generated by scripts/gen-registry.mjs.
// PORT: regenerated by pele-kotlin/scripts/gen_registry.py, listing only the ported types.
val all: List<Diagram<*>> = listOf(
{body})
''')
print(len(ported), 'types:', ', '.join(ported))
